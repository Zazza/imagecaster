let serverJobSeq = 0

async function streamServerJob(run, onProgress) {
  const jobID = `${Date.now()}-${++serverJobSeq}`
  const off = EventsOn(`server:download:progress:${jobID}`, (data) => {
    const p = parseProgress(data)
    onProgress(p.text, p.percent)
  })
  try {
    await run(jobID)
  } finally {
    off()
  }
}

